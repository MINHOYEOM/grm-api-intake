-- ============================================================================
-- 069 — 캐나다 실사: 이미 갖고 있던 실사일을 제 칸에 넣는다
--
-- ★"캐나다 실사일을 수집하라"로 착수했는데 **수집할 것이 없었다.** 원천을 직접 찔러
--   확인한 사실:
--     · 목록 API 가 `inspectionStartDate` 를 준다 — 전 행(표본 1,528/1,528).
--     · `inspectionEndDate` 는 **전 행이 null** 이다. 캐나다는 종료일을 공개하지 않는다.
--     · 형식은 `/Date(1787673600000-0400)/` 로, 수집기의 `parse_dotnet_date` 가 이미
--       정확히 읽고 있다. 수집은 건강하다.
--
-- 그럼 왜 `inspection_date` 가 비어 있었나 — **수집기가 그 값을 `published_date` 에
-- 넣기 때문이다**(`collect_hc_inspection_backfill.py`: `published_date =
-- parse_dotnet_date(row.get("inspectionStartDate"))`). 즉 캐나다 문서의 "공개일"은
-- 처음부터 공개일이 아니라 **실사 시작일**이었다.
--
-- ★그래서 이 마이그레이션이 고치는 것은 결손이 아니라 **거짓말**이다. 화면은 그 날짜에
--   "공개"라고 적고 있었다(문서 1,824건 · 발행면 1,330장). 2021-01-04 ~ 2026-07-21.
--
-- ── 왜 빈 칸으로 두지 않고 채우는가 ────────────────────────────────────────
-- 빈 `inspection_date` 는 "우리가 실사일을 모른다"는 **단정**이다(부재 어휘 규율).
-- 캐나다는 알고 있다 — 다만 다른 칸에 들어 있었을 뿐이다. 아는 것을 모른다고 말하지
-- 않는다. 채우고 나면 표시층이 이미 갖춘 규칙(`doc_display_date`)이 그대로 옳게 돈다.
--
-- ★두 칸이 **같은 값**이 되는 것은 의도다 — 캐나다는 날짜가 하나뿐이라는 뜻이고,
--   표시층은 "같으면 한 번만, 그리고 실사라고" 말하도록 함께 고친다. 두 번 적으면서
--   한쪽을 '공개'라고 부르면 지금과 똑같은 거짓말이 된다.
--
-- ── 시작일이지 종료일이 아니다 ─────────────────────────────────────────────
-- 다른 소스의 `inspection_date` 는 종료일 계열이다(FDA 483 = 발부일 = 실사 종료,
-- MFDS·EU·MHRA = 종료일). 캐나다만 시작일이다 — 원천이 종료일을 안 주기 때문이고,
-- 없는 값을 지어내지 않는다. 실사 하나의 시작과 끝은 며칠 차이라 "언제 실사받았나"에는
-- 시작일로 충분하고, 그 차이를 감추지 않으려고 이 주석과 칼럼 코멘트에 적어 둔다.
--
-- 멱등: 이미 같은 값이면 갱신하지 않는다.
-- ============================================================================

update public.findings
   set inspection_date = published_date
 where source = 'Health Canada Inspection'
   and coalesce(published_date, '') ~ '^[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]$'
   and coalesce(inspection_date, '') is distinct from published_date;

comment on column public.findings.inspection_date is
  '규제기관이 실사한 날. FDA 483=발부일(실사 종료), EU/MHRA NCR·MFDS=실사 종료일, '
  '캐나다 실사=실사 **시작**일(원천이 종료일을 주지 않는다). YYYY-MM-DD 또는 빈 문자열. '
  'published_date(우리가 문서를 확보한 날)와 다른 축이며 대체하지 않는다 — 다만 캐나다는 '
  'published_date 에 실사 시작일이 들어 있어 두 칸의 값이 같다.';
